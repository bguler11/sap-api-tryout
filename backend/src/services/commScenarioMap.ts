function stripSuffix(name: string): string {
  return name
    .replace(/_SRV_\d+$/, '')
    .replace(/_\d+$/, '')
    .replace(/_SRV$/, '');
}

export function getCommScenario(serviceName: string): string | null {
  try {
    const { getCommScenarioByName } = require('./db.service');
    const row = getCommScenarioByName(serviceName);
    if (row) return row.scenario_id;
  } catch {}

  const key = serviceName.toUpperCase();

  if (COMM_SCENARIO_MAP[key]) return COMM_SCENARIO_MAP[key];

  const stripped = stripSuffix(key);
  if (stripped !== key && COMM_SCENARIO_MAP[stripped]) return COMM_SCENARIO_MAP[stripped];

  return null;
}
